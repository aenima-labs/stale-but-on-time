#!/usr/bin/env python3
"""Build the anonymised review copy of this repository.

    uv run inv paper.anon   (or: uv run python src/make_anon.py)

Writes, under dist/ (git-ignored):
    anon/                          the anonymised tree (no git history)
    stale-but-on-time-anon.zip     the same tree, for a supplementary-material upload
    stale-but-on-time-anon.pdf     the paper built in double-blind mode

What changes in the copy:
  * paper/identity.tex becomes anonymous, so the build uses [tmlr] without `preprint`,
    "Anonymous authors", and generic names for the product and the framework;
  * names, organisation, URLs and the pack id are replaced in text files, and every
    sealed result bundle that this touches is re-sealed and re-verified;
  * the product name is replaced everywhere: "[PRODUCT NAME]" where it stands as a word
    (prompts, replies), "product" inside identifiers, and in file and folder names
    (results/e3-kodama becomes results/e3-product);
  * the Circumstances framework is vendored from the pinned commit, with its authorship removed;
  * README and pyproject.toml are replaced by anonymous versions, and src/fetch_data.py loses
    its release URL (the review copy has no release);
  * the final scan fails the build if any identifying string is left in any file or in the PDF.
Results, numbers and code logic are not altered. Needs git, uv and tectonic.
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
OUT = DIST / "anon"
sys.path.insert(0, str(ROOT / "src"))

# Order matters: longer strings first.
SUBS = [
    ("aenima/async-recall", "anon/async-recall"),
    ("Aenima Labs", "Anonymous"),
    ("https://aenimalabs.com", "https://anonymous.invalid"),
    ("aenimalabs.com", "anonymous.invalid"),
    ("aenima-labs", "anonymous"),
    ("You are Kodama,", "You are [PRODUCT NAME],"),
]
# The product name. As a word of its own it is a name someone says or reads; inside an
# identifier (event names, pack ids, folder names, variables) it becomes "product".
PRODUCT = [
    (re.compile(r"(?:(?<![A-Za-z0-9_./-])|(?<=\\[nt]))Kodama(?![A-Za-z0-9_/-])"), "[PRODUCT NAME]"),
    (re.compile(r"KODAMA"), "PRODUCT"),
    (re.compile(r"Kodama"), "Product"),
    (re.compile(r"kodama"), "product"),
]
VENDORED = [(re.compile(r"kodama", re.IGNORECASE), "product")]
IDENTIFYING = re.compile(rb"aenima|kodama|chernov|lebeg|/Users/", re.IGNORECASE)
TEXT_SUFFIXES = {".py", ".md", ".tex", ".yaml", ".yml", ".toml", ".sh", ".json", ".jsonl",
                  ".bib", ".txt", ".csv", ".log", ".cff", ".tf", ".hcl"}
TEXT_NAMES = {"LICENSE", "Dockerfile"}
SKIP = {"paper/main.pdf", "src/make_anon.py", "uv.lock"}

IDENTITY = r"""% Anonymous identity for double-blind review (generated by src/make_anon.py).
\newif\ifanon
\anontrue
\newcommand{\product}{our voice companion}
\newcommand{\Product}{Our voice companion}
\newcommand{\promptname}{[PRODUCT NAME]}
\newcommand{\framework}{the evaluation framework}
\newcommand{\paperauthor}{\name Anonymous authors \\
      \addr Anonymous institution}
"""

README = """# Stale but on Time (anonymised review copy)

Supplementary material for the paper in `paper/main.pdf`. Author, institution and
product names are removed. The product name is shown as `[PRODUCT NAME]` in the quoted
system prompt (`src/subject.py`) and in stored replies, and as `product` in identifiers
and folder names; the stored results were produced with the real name. Bundles changed
this way were sealed again, so their seals verify but differ from the originals.
The product's source code is not part of this copy, so Experiment 3 can be re-analysed
from its bundles but not re-run.

## Layout

| Path | What it is |
|---|---|
| `pack-src/`, `pack/`, `fixtures/` | Fictional memory store and the 40-case test pack |
| `src/` | Retriever, Experiment 1 (LoCoMo replay), Experiment 2 (reference agent and runner), Experiment 3 (analysis of the runs against the product), figures |
| `results/` | Per-utterance retrievals (E1), sealed run bundles with every trial (E2: `e2`, `e2-think`, `e2-qwen3`, `e2-anthropic`; E3: `e3-product`, `e3-product-run1`), summaries |
| `vendor/circumstances/` | The evaluation framework, vendored at the commit used |
| `paper/` | LaTeX sources, generated tables, number macros |

"Memorome", in file names, code and result events, is the term of Xiao et al. (2026),
"Memory is Not Search", Section 2, for the whole collection of one person's memories.
Here it is the store of 48 notes.

## Reproduce

Needs `uv`, `tectonic` and, only for re-running Experiments 1 and 2, a local Ollama with
`nomic-embed-text`, `gemma4:e4b` and `qwen3:8b`.

```bash
uv sync
uv run inv data.fetch   # downloads LoCoMo (CC BY-NC 4.0, not redistributed)
uv run inv analyze      # analysis, figures, numbers, paper
```

`uv run inv --list` shows the other tasks.

Re-running the replay and the agent trials from scratch takes about 30 minutes
(`uv run inv reproduce`); the model is local, so trial text is not bit-identical.
"""


def drop_release_url(path: Path) -> None:
    """The review copy has no release to fetch the embedding cache from."""
    text = re.sub(r"^REPO: str \| None = .*$", "REPO: str | None = None", path.read_text(), flags=re.MULTILINE)
    path.write_text(text)


def run(cmd: list[str], cwd: Path | None = None) -> str:
    done = subprocess.run(cmd, cwd=cwd, check=True, capture_output=True, text=True)
    return done.stdout


def tracked_files() -> list[str]:
    names = run(["git", "ls-files", "-z"], cwd=ROOT).split("\0")
    return [n for n in names if n and n not in SKIP and (ROOT / n).is_file()]


def substitute(text: str) -> str:
    for old, new in SUBS:
        text = text.replace(old, new)
    return text


def anon_name(name: str) -> str:
    """The path of a tracked file inside the anonymised tree."""
    return re.sub(r"kodama", "product", name, flags=re.IGNORECASE)


def rewrite_texts(root: Path, patterns: list[tuple[re.Pattern, str]]) -> None:
    for path in sorted(root.rglob("*")):
        if not path.is_file() or (path.suffix not in TEXT_SUFFIXES and path.name not in TEXT_NAMES):
            continue
        old = path.read_text(encoding="utf-8")
        new = substitute(old)
        for pattern, repl in patterns:
            new = pattern.sub(repl, new)
        if new != old:
            path.write_text(new, encoding="utf-8")


def vendor_circumstances(pin: dict) -> None:
    url, rev = pin["git"], pin["rev"]
    with tempfile.TemporaryDirectory() as tmp:
        checkout = Path(tmp) / "c"
        run(["git", "clone", "--quiet", url, str(checkout)])
        run(["git", "checkout", "--quiet", rev], cwd=checkout)
        target = OUT / "vendor" / "circumstances"
        shutil.copytree(
            checkout / "src", target / "src",
            ignore=shutil.ignore_patterns("__pycache__", "*.pyc"),
        )
        for name in ("pyproject.toml", "LICENSE"):
            shutil.copy2(checkout / name, target / name)
    rewrite_texts(target, VENDORED)
    manifest = target / "pyproject.toml"  # the README is not vendored
    manifest.write_text(re.sub(r'^readme = .*\n', "", manifest.read_text(), flags=re.MULTILINE))


def anonymise_pyproject() -> None:
    path = OUT / "pyproject.toml"
    text = path.read_text()
    text = re.sub(
        r"^circumstances = \{ git = .*\}$",
        'circumstances = { path = "vendor/circumstances", editable = true }',
        text,
        flags=re.MULTILINE,
    )
    path.write_text(text)


def reseal_bundles() -> int:
    from scrub_paths import reseal
    from circumstances.artifacts import verify_bundle

    count = 0
    for seal in sorted((OUT / "results").glob("*/*/*/seal.json")) + sorted(
        (OUT / "results").glob("*/*/seal.json")
    ):
        reseal(seal.parent)
        problems = verify_bundle(seal.parent)
        if problems:
            raise SystemExit(f"{seal.parent}: {problems}")
        count += 1
    return count


def build_pdf() -> Path:
    paper = OUT / "paper"
    run(["tectonic", "main.tex"], cwd=paper)
    pdf = DIST / "stale-but-on-time-anon.pdf"
    shutil.copy2(paper / "main.pdf", pdf)
    for junk in paper.glob("*.aux"):
        junk.unlink()
    return pdf


def pdf_text(path: Path) -> bytes:
    """Extract text and metadata from a PDF with pdftotext, or pypdf through uv."""
    if shutil.which("pdftotext"):
        return subprocess.run(["pdftotext", str(path), "-"], capture_output=True, check=True).stdout
    code = (
        "import sys, pypdf; r = pypdf.PdfReader(sys.argv[1]); "
        "print(r.metadata); print('\\n'.join(p.extract_text() for p in r.pages))"
    )
    return subprocess.run(
        ["uv", "run", "--quiet", "--no-project", "--with", "pypdf", "python", "-c", code, str(path)],
        capture_output=True, check=True,
    ).stdout


def audit(pdf: Path) -> list[str]:
    hits = []
    for path in sorted(OUT.rglob("*")):
        if path.is_file() and IDENTIFYING.search(path.read_bytes()):
            hits.append(str(path.relative_to(OUT)))
        if IDENTIFYING.search(path.name.encode()):
            hits.append(f"(name) {path.relative_to(OUT)}")
    for target in (pdf, OUT / "paper" / "main.pdf"):
        if IDENTIFYING.search(pdf_text(target)):
            hits.append(f"(pdf text) {target.name}")
    if IDENTIFYING.search(pdf.read_bytes()):
        hits.append(f"(pdf bytes/metadata) {pdf.name}")
    return hits


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    for name in tracked_files():
        target = OUT / anon_name(name)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / name, target)

    pin = tomllib.loads((ROOT / "pyproject.toml").read_text())["tool"]["uv"]["sources"]["circumstances"]
    rewrite_texts(OUT, PRODUCT)
    (OUT / "paper" / "identity.tex").write_text(IDENTITY)
    (OUT / "README.md").write_text(README)
    drop_release_url(OUT / "src" / "fetch_data.py")
    vendor_circumstances(pin)
    anonymise_pyproject()
    sealed = reseal_bundles()
    if shutil.which("uv"):
        run(["uv", "lock"], cwd=OUT)
    pdf = build_pdf()

    hits = audit(pdf)
    if hits:
        print("Identifying strings remain:\n  " + "\n  ".join(hits), file=sys.stderr)
        raise SystemExit(1)

    archive = DIST / "stale-but-on-time-anon.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(OUT.rglob("*")):
            if path.is_file() and ".venv" not in path.parts:
                z.write(path, Path("stale-but-on-time") / path.relative_to(OUT))
    print(f"re-sealed and verified {sealed} bundles")
    print(f"{pdf.relative_to(ROOT)}  {pdf.stat().st_size // 1024} KB")
    print(f"{archive.relative_to(ROOT)}  {archive.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
